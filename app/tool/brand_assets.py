"""Generates every Sora logo asset from the logo handoff's mark.

    python tool/brand_assets.py      (needs Pillow; run from the app/ folder)

The mark (assets/brand/sora-mark-*.svg; 120 x 120 viewBox for the icons): inside
`translate(60 60) scale(.72) translate(-60 -67)`, two half rings centred at (60, 86) — r 38 and
r 22 (the inner at 55% opacity), stroke 7 with round caps — over a half disc of r 10.
The app icon is the mark on a black tile with rx 27. Keep in sync with lib/brand/sora_logo.dart.
"""

import math
from pathlib import Path

from PIL import Image, ImageDraw

APP = Path(__file__).resolve().parents[1]
RES = APP / "android" / "app" / "src" / "main" / "res"

CENTRE = (60.0, 86.0)
RINGS = [(38.0, 1.0), (22.0, 0.55)]  # radius, opacity
STROKE, R_CORE = 7.0, 10.0
WHITE, CYAN, BLACK = (255, 255, 255), (92, 200, 255), (0, 0, 0)


def to_view(x: float, y: float) -> tuple[float, float]:
    """Inner mark coordinates → the 120-unit viewBox."""
    return 60 + 0.72 * (x - 60), 60 + 0.72 * (y - 67)


def render(size: int, fit: float = 1.0, tile: str = "rounded", ss: int = 8) -> Image.Image:
    """The mark on a black tile: tile = "rounded" (rx 27 of 120), "square", "round" or "none".
    `fit` = share of the image the 120 viewBox covers."""
    big = size * ss
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    k, off = big * fit / 120, big * (1 - fit) / 2
    box = [off, off, off + 120 * k - 1, off + 120 * k - 1]
    if tile == "rounded":
        d.rounded_rectangle(box, radius=27 * k, fill=BLACK + (255,))
    elif tile == "square":
        d.rectangle([0, 0, big, big], fill=BLACK + (255,))
    elif tile == "round":
        d.ellipse(box, fill=BLACK + (255,))

    def px(x: float, y: float) -> tuple[float, float]:
        vx, vy = to_view(x, y)
        return off + vx * k, off + vy * k

    # Rings: stamp round dabs densely along each half circle (seamless round-capped stroke).
    rw = STROKE * 0.72 * k / 2
    for radius, opacity in RINGS:
        colour = tuple(round(c * opacity) for c in WHITE) + (255,)  # on black, opacity = darker grey
        steps = int(math.pi * radius * 0.72 * k / (rw * 0.15)) + 1
        for i in range(steps + 1):
            a = math.pi + math.pi * i / steps  # 180° → 360°: left, over the top, to the right
            x, y = px(CENTRE[0] + radius * math.cos(a), CENTRE[1] + radius * math.sin(a))
            d.ellipse([x - rw, y - rw, x + rw, y + rw], fill=colour)
    cx, cy = px(*CENTRE)
    r = R_CORE * 0.72 * k
    d.pieslice([cx - r, cy - r, cx + r, cy + r], 180, 360, fill=CYAN + (255,))
    return img.resize((size, size), Image.LANCZOS)


def vector(size_dp: int, viewport: float, fit: float, mono: bool = False) -> str:
    """Android VectorDrawable of the mark; the 120 viewBox scaled to `fit` × viewport, centred."""
    s = viewport * fit / 120
    t = viewport * (1 - fit) / 2
    core = "#FFFFFF" if mono else "#5CC8FF"
    rings = "\n".join(
        f'''                <path android:strokeColor="#FFFFFF" android:strokeAlpha="{opacity:g}" android:strokeWidth="{STROKE:g}"
                    android:strokeLineCap="round" android:pathData="M{60 - radius:g},86 A{radius:g},{radius:g} 0 0,1 {60 + radius:g},86"/>'''
        for radius, opacity in RINGS
    )
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand_assets.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp" android:height="{size_dp}dp"
    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">
    <group android:translateX="{t:.3f}" android:translateY="{t:.3f}" android:scaleX="{s:.4f}" android:scaleY="{s:.4f}">
        <group android:translateX="60" android:translateY="60" android:scaleX="0.72" android:scaleY="0.72">
            <group android:translateX="-60" android:translateY="-67">
{rings}
                <path android:fillColor="{core}" android:pathData="M50,86 A10,10 0 0,1 70,86 Z"/>
            </group>
        </group>
    </group>
</vector>
'''


def main() -> None:
    brand = APP / "assets" / "brand"
    brand.mkdir(parents=True, exist_ok=True)
    render(1024).save(brand / "sora-icon-1024.png")

    # Legacy launcher icons (pre-Android 8): black square and round variants.
    for folder, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        render(px, tile="square").save(RES / f"mipmap-{folder}" / "ic_launcher.png")
        render(px, tile="round").save(RES / f"mipmap-{folder}" / "ic_launcher_round.png")

    # Adaptive icon (Android 8+): black background; the launcher shows the middle 72 of 108 dp.
    drawable = RES / "drawable"
    (drawable / "ic_launcher_foreground.xml").write_text(vector(108, 108, 0.9), encoding="utf-8")
    (drawable / "ic_launcher_monochrome.xml").write_text(vector(108, 108, 0.9, mono=True), encoding="utf-8")
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
'''
    (anydpi / "ic_launcher.xml").write_text(adaptive, encoding="utf-8")
    (anydpi / "ic_launcher_round.xml").write_text(adaptive, encoding="utf-8")

    # Windows app icon: the rounded black tile, like the logo handoff's app icon.
    ico = APP / "windows" / "runner" / "resources" / "app_icon.ico"
    render(256).save(ico, sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    print("brand assets written")


if __name__ == "__main__":
    main()
