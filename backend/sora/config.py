"""Settings, loaded from the repo-root .env file (never committed)."""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from zoneinfo import ZoneInfo

from pydantic_settings import BaseSettings, SettingsConfigDict

ROOT_DIR = Path(__file__).resolve().parents[2]
ENV_FILE = ROOT_DIR / ".env"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=ENV_FILE, env_file_encoding="utf-8-sig", extra="ignore"
    )

    # --- Server ---
    host: str = "127.0.0.1"
    port: int = 8000
    # URL the phone/browser uses to reach this server (Tailscale URL in production).
    public_base_url: str = "http://localhost:8000"
    timezone: str = "Asia/Dhaka"
    owner_name: str = ""
    # Language for notifications and email summaries; chat replies follow whatever language the owner uses.
    assistant_language: str = "Bangla"
    data_dir: Path = ROOT_DIR / "data"
    log_level: str = "INFO"

    # --- Storage / secrets ---
    database_url: str = ""
    # Windows without Docker: name of the WSL distro running Postgres; Sora keeps it awake.
    wsl_distro: str = ""
    encryption_key: str = ""  # Fernet key, generated by `python -m sora setup`

    # --- LLM (any OpenAI-compatible endpoint; OpenRouter by default) ---
    llm_base_url: str = "https://openrouter.ai/api/v1"
    llm_api_key: str = ""
    llm_model: str = ""
    llm_fast_model: str = ""  # cheap model for email triage; falls back to llm_model
    llm_temperature: float = 0.4
    llm_stream: bool = True
    llm_max_tool_rounds: int = 8
    # OpenRouter reasoning control: "" = model default, or none | low | medium | high.
    # Reasoning tokens are billed as output, so "low"/"none" keeps a chatty assistant cheap and fast.
    llm_reasoning: str = "low"
    # OpenRouter routing. Fallback models are tried in order if the main one errors or is down.
    llm_fallback_models: str = ""
    # "deny" = only providers that don't store or train on prompts (your emails pass through the LLM).
    llm_data_collection: str = "deny"
    # Allowed quantizations for open-weight models, e.g. "fp8,fp16,bf16,fp32" to skip lossy fp4/int4 hosts.
    llm_quantizations: str = ""
    llm_timeout_seconds: float = 120.0
    # The owner's university notice board (university_notices tool).
    notice_board_url: str = "https://green.edu.bd/notice"
    # Model that reads PC screenshots; must accept images. "" = the first fallback model, else llm_model.
    vision_model: str = ""
    # The web_search tool: brave | tavily (both need web_search_api_key) | duckduckgo (no key). DuckDuckGo is
    # also the fallback when the keyed provider fails.
    web_search_provider: str = "duckduckgo"
    web_search_api_key: str = ""

    # --- Embeddings (RAG) ---
    embedding_base_url: str = "https://openrouter.ai/api/v1"
    embedding_api_key: str = ""  # falls back to llm_api_key
    embedding_model: str = "openai/text-embedding-3-small"
    embedding_dim: int = 1536
    # Ask the model for exactly embedding_dim dimensions (OpenAI v3 and Gemini embedding models support this).
    embedding_send_dimensions: bool = False

    # --- Google ---
    google_client_id: str = ""
    google_client_secret: str = ""
    google_redirect_uri: str = ""  # defaults to {public_base_url}/oauth/google/callback

    # --- Background jobs ---
    email_watcher_enabled: bool = True
    gmail_poll_seconds: int = 90
    # Gmail categories that are recorded but never sent to the LLM or pushed.
    triage_skip_labels: str = "CATEGORY_PROMOTIONS,CATEGORY_SOCIAL,SPAM"
    reminder_poll_seconds: int = 20

    # --- Push notifications (Firebase Cloud Messaging, optional) ---
    fcm_service_account_file: str = ""

    # --- Voice ---
    stt_provider: str = "groq"  # groq | openai | local | none
    stt_base_url: str = "https://api.groq.com/openai/v1"
    stt_api_key: str = ""
    stt_model: str = "whisper-large-v3-turbo"
    stt_language: str = ""  # "" = auto-detect, or "bn" / "en"
    whisper_local_model: str = "large-v3-turbo"
    whisper_model_dir: str = ""  # keep big model files off C: if space is tight
    # The on-device "Hey Sora" model's score that counts as its name (the PC agent and the phone both use it)
    wake_threshold: float = 0.5
    tts_voice_bn: str = "bn-BD-NabanitaNeural"
    tts_voice_en: str = "en-US-AvaMultilingualNeural"

    # ---- derived ----
    @property
    def tz(self) -> ZoneInfo:
        return ZoneInfo(self.timezone)

    @property
    def async_database_url(self) -> str:
        url = self.database_url
        for prefix in ("postgresql://", "postgres://"):
            if url.startswith(prefix):
                return "postgresql+psycopg://" + url[len(prefix):]
        return url

    @property
    def google_redirect(self) -> str:
        return self.google_redirect_uri or f"{self.public_base_url.rstrip('/')}/oauth/google/callback"

    @property
    def google_configured(self) -> bool:
        return bool(self.google_client_id and self.google_client_secret)

    @property
    def llm_configured(self) -> bool:
        return bool(self.llm_api_key and self.llm_model)

    @property
    def fast_model(self) -> str:
        return self.llm_fast_model or self.llm_model

    @property
    def vision_model_name(self) -> str:
        fallbacks = [m.strip() for m in self.llm_fallback_models.split(",") if m.strip()]
        return self.vision_model or (fallbacks[0] if fallbacks else self.llm_model)

    @property
    def embedding_key(self) -> str:
        return self.embedding_api_key or self.llm_api_key

    @property
    def files_dir(self) -> Path:
        path = self.data_dir / "files"
        path.mkdir(parents=True, exist_ok=True)
        return path


@lru_cache
def get_settings() -> Settings:
    return Settings()
